export function chatSystemPrompt(title: string, kind: Scenario, transcript: string, notes?: string): string {
  return `Ты помощник по аудиозаписи «${title}» (${SPECS[kind].kind}).
Отвечай кратко и по делу, на языке вопроса.
Опирайся на запись. Если в записи ответа нет, скажи об этом. Можешь дополнить ответ общими знаниями, но явно пометь такую часть словами «Не из записи:».
Ссылайся на моменты записи в формате [мм:сс].
Для списков и выделения используй Markdown.

Расшифровка (#номер [время] текст):
${transcript}${notes ? `\n\nКонспект:\n${notes}` : ''}`;
}
