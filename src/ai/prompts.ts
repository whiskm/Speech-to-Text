import type { Scenario } from '../lib/types';

export const SYSTEM_PROMPT = `Ты помогаешь человеку разобрать аудиозапись.
Тебе дают автоматическую расшифровку, разбитую на пронумерованные реплики вида «#номер [мм:сс] текст».
В расшифровке бывают ошибки распознавания, повторы и обрывки фраз. Исправляй очевидные ошибки по смыслу, но ничего не выдумывай и не добавляй фактов, которых нет в записи.
Пиши на том языке, на котором звучит основная речь записи.
Время указывай в формате «мм:сс» или «ч:мм:сс», беря его из меток реплик.
Отвечай только JSON-объектом, без пояснений и без Markdown-обёртки.`;

const NOISE_FIELD = `"noise": [номера реплик],`;
const NOISE_RULE = `В "noise" перечисли номера реплик, которые не относятся к основной речи: разговоры и реплики из зала, посторонние голоса, обрывки чужих фраз, шум. Если таких нет, верни пустой список. Не помечай вопросы слушателей, на которые отвечает основной говорящий.`;

const SPECS: Record<Scenario, { kind: string; json: string; rules: string }> = {
  lecture: {
    kind: 'лекция или урок',
    json: `{
  "title": "...",
  ${'{noise}'}
  "brief": [{"text": "...", "time": "мм:сс"}],
  "notes": "...",
  "terms": [{"term": "...", "definition": "..."}]
}`,
    rules: `"title": тема лекции, до 6 слов.
"brief": от 3 до 5 главных мыслей, каждая одним предложением, с временем, где она прозвучала.
"notes": подробный конспект в Markdown. Разделы «## Тема», списки, определения, формулы обычным текстом (например ΔU = Q − A). Если лектор задал что-то на дом или сказал, что будет на экзамене, добавь в конце раздел «## Что сделать».
"terms": термины и их определения из лекции, по одному предложению. Если терминов нет, верни пустой список.`,
  },
  meeting: {
    kind: 'рабочая встреча',
    json: `{
  "title": "...",
  ${'{noise}'}
  "brief": [{"text": "...", "time": "мм:сс"}],
  "decisions": ["..."],
  "tasks": [{"text": "...", "who": "...", "due": "...", "time": "мм:сс"}],
  "questions": ["..."]
}`,
    rules: `"title": о чём встреча, до 6 слов.
"brief": от 3 до 5 главных итогов одним предложением, с временем.
"decisions": принятые решения, каждое одним предложением.
"tasks": задачи. "who" — имя исполнителя, как его назвали, или "не назначено". "due" — срок так, как его сказали ("до пятницы", "25 ноября"), или пустая строка. "time" — где прозвучала задача.
"questions": вопросы, которые остались без ответа. Пустой список, если таких нет.`,
  },
  talk: {
    kind: 'разговор',
    json: `{
  "title": "...",
  ${'{noise}'}
  "brief": [{"text": "...", "time": "мм:сс"}],
  "notes": "..."
}`,
    rules: `"title": о чём разговор, до 6 слов.
"brief": от 3 до 5 главных мыслей одним предложением, с временем.
"notes": итоги в Markdown с разделами «## О чём договорились», «## Что говорила каждая сторона», «## Что осталось открытым». Пропусти раздел, если для него нет содержания.`,
  },
  note: {
    kind: 'голосовая заметка',
    json: `{
  "title": "...",
  ${'{noise}'}
  "brief": [{"text": "...", "time": "мм:сс"}],
  "notes": "..."
}`,
    rules: `"title": суть заметки, до 6 слов.
"brief": от 1 до 3 главных мыслей одним предложением, с временем.
"notes": чистый текст заметки. Убери слова-паразиты, повторы и оговорки, разбей на абзацы. Сохрани смысл, порядок мыслей и стиль автора. Без заголовков.`,
  },
};

export function buildPrompt(scenario: Scenario, transcript: string, withNoise: boolean): string {
  const s = SPECS[scenario];
  const json = s.json.replace('{noise}', withNoise ? NOISE_FIELD : '').replace(/\n\s*\n/g, '\n');
  return `Тип записи: ${s.kind}.
Верни JSON строго такого вида:
${json}

Правила:
${withNoise ? NOISE_RULE + '\n' : ''}${s.rules}

Расшифровка:
${transcript}`;
}

/** First pass for long recordings: notes for one part, keeping the time marks. */
export function buildPartPrompt(scenario: Scenario, part: string, n: number, total: number, withNoise: boolean): string {
  return `Тип записи: ${SPECS[scenario].kind}. Это часть ${n} из ${total} длинной записи.
Верни JSON строго такого вида:
{
  ${withNoise ? NOISE_FIELD : ''}
  "notes": "..."
}

Правила:
${withNoise ? NOISE_RULE + '\n' : ''}"notes": подробный конспект этой части в Markdown. У каждого пункта в начале поставь время в квадратных скобках, например «[12:40]». Сохрани все факты, имена, числа, сроки и формулы.

Расшифровка части:
${part}`;
}

/** Second pass for long recordings: the usual result built from part notes. */
export function buildMergePrompt(scenario: Scenario, partNotes: string): string {
  const s = SPECS[scenario];
  const json = s.json.replace('{noise}', '').replace(/\n\s*\n/g, '\n');
  return `Тип записи: ${s.kind}. Запись длинная, поэтому вместо расшифровки даны конспекты её частей. Время в квадратных скобках — метки записи.
Верни JSON строго такого вида:
${json}

Правила:
${s.rules}

Конспекты частей:
${partNotes}`;
}

